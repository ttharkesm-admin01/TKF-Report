/**
 * สไลด์ตัดเนื้อหาที่ล้นทิ้งเงียบ ๆ ไม่มี error (`.claude/skills/verify`)
 * ข้อความยาวจึงต้องหดตัวเอง และหน้า `/edit` ต้องรู้ล่วงหน้าว่าหดแล้วยังไม่พอ
 *
 * เดิมใช้ "จำนวนตัวอักษร" ตัดสิน แต่พังทันทีเมื่อเจอหัวข้อย่อยสั้น ๆ หลายข้อ —
 * 30 บรรทัดสั้นกินที่มากกว่าย่อหน้ายาว 1,400 ตัวอักษรเกือบเท่าตัว
 * ตัวที่ต้องนับจริงคือ **จำนวนบรรทัดหลังตัดคำ** ไม่ใช่จำนวนตัวอักษร
 *
 * ค่าคงที่ทั้งสามวัดจริงในเบราว์เซอร์ที่ `/deck` ไม่ได้คำนวณจากสูตร
 * และอยู่ในหน่วย cqw ทั้งหมดจึงไม่ผูกกับขนาดจอ — สไลด์เป็น 16:9 คงที่เสมอ
 */

/** ความสูงที่เหลือให้เนื้อหาหลังหักหัวเรื่องกับแถบท้าย (วัดได้ 415px จากสไลด์กว้าง 1118px) */
const AVAIL_CQW = 37;

/**
 * ตัวอักษรไทยต่อบรรทัด × ขนาดตัวอักษร ≈ คงที่ · วัดได้ 186–193 ทุกขนาด ใช้ 188
 * ไม่ต้องหักเผื่อเพิ่มอีก เพราะการปัดเศษบรรทัดของทุกย่อหน้าเผื่อให้อยู่แล้ว
 */
const CHARS_PER_LINE_CQW = 188;

/** ช่องไฟระหว่างย่อหน้า และระหว่างหัวข้อย่อยในรายการเดียวกัน */
const PART_GAP = 1.2;
const ITEM_GAP = 0.6;

/** ขนาดที่ยอมให้ใช้ เรียงจากใหญ่ไปเล็ก · ตัวสุดท้าย ≈ 12.5pt บนสไลด์ 960pt คือพื้นล่างที่ยังอ่านออกตอนฉาย */
const SIZES = [2.2, 2, 1.8, 1.6, 1.45, 1.3] as const;

/** ความสูงที่ข้อความจะกินถ้าใช้ขนาดนี้ (หน่วย cqw) */
function heightAt(parts: TextPart[], size: number): number {
  const perLine = CHARS_PER_LINE_CQW / size;
  let lines = 0;
  let gaps = Math.max(0, parts.length - 1) * PART_GAP;

  for (const p of parts) {
    if (p.kind === 'para') {
      lines += Math.max(1, Math.ceil(p.text.length / perLine));
    } else {
      // หัวข้อย่อยขึ้นบรรทัดใหม่เสมอ ต่อให้ข้อความสั้นแค่คำเดียว
      for (const item of p.items) lines += Math.max(1, Math.ceil(item.length / perLine));
      gaps += Math.max(0, p.items.length - 1) * ITEM_GAP;
    }
  }
  return lines * 1.6 * size + gaps;
}

export interface BodyFit {
  /** ขนาดตัวอักษรที่จะใช้จริง เช่น `1.8cqw` */
  size: string;
  /** ย่อจนเล็กสุดแล้วยังไม่พอ — ส่วนที่เกินจะถูกตัดหาย */
  overflow: boolean;
}

/**
 * เผื่อหนึ่งบรรทัดก่อนจะเตือนว่าล้น
 *
 * การเดาจำนวนบรรทัดจากจำนวนตัวอักษรคลาดได้ ±1 บรรทัดต่อย่อหน้า เพราะปัดเศษขึ้นเสมอ
 * เอียงไปทาง "เล็กไว้ก่อน" ตอนเลือกขนาดถือว่าดี (แค่ตัวหนังสือเล็กลงนิดเดียว)
 * แต่ถ้าเอาเกณฑ์เดียวกันไปขึ้นคำเตือนที่ `/edit` จะฟ้องทั้งที่ของจริงยังพอดีอยู่
 * คำเตือนจึงรอจนเกินจริง ๆ ราวหนึ่งบรรทัด
 */
const OVERFLOW_SLACK = 1.08;

/** เลือกขนาดตัวอักษรที่ใหญ่ที่สุดที่ยังพอดีกรอบ */
export function fitBody(parts: TextPart[]): BodyFit {
  for (const size of SIZES) {
    if (heightAt(parts, size) <= AVAIL_CQW) return { size: `${size}cqw`, overflow: false };
  }
  const min = SIZES[SIZES.length - 1];
  return {
    size: `${min}cqw`,
    overflow: heightAt(parts, min) > AVAIL_CQW * OVERFLOW_SLACK,
  };
}
