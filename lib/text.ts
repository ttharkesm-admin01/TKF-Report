/**
 * text.ts — แปลงข้อความดิบของบล็อก `text` เป็นย่อหน้ากับรายการหัวข้อย่อย
 *
 * บล็อกนี้เป็นชนิดเดียวในเด็คที่เนื้อหาเป็นข้อความล้วน ผู้ใช้พิมพ์เองที่หน้า `/edit`
 * จึงรับได้แค่รูปแบบที่พิมพ์ในกล่องข้อความธรรมดาได้ ไม่ใช่ Markdown เต็มรูปแบบ:
 *
 *   - บรรทัดว่างคั่น = ขึ้นย่อหน้าใหม่
 *   - บรรทัดที่ขึ้นต้นด้วย `-` `•` หรือ `*` = หัวข้อย่อย
 *
 * แยกมาไว้นอกคอมโพเนนต์เพราะ `/edit` ต้องใช้ตัวเดียวกันนับบรรทัดตอนเตือนว่าข้อความยาวเกิน
 */

export type TextPart =
  | { kind: 'para'; text: string }
  | { kind: 'list'; items: string[] };

const BULLET = /^\s*[-•*]\s+/;

/** ตัดข้อความดิบเป็นย่อหน้า/รายการตามกฎข้างบน · ข้อความว่างคืนอาร์เรย์ว่าง */
export function parseBody(body: string): TextPart[] {
  const out: TextPart[] = [];

  for (const chunk of body.replace(/\r\n?/g, '\n').split(/\n\s*\n/)) {
    const lines = chunk.split('\n').map((l) => l.trim()).filter(Boolean);
    if (lines.length === 0) continue;

    if (lines.every((l) => BULLET.test(l))) {
      out.push({ kind: 'list', items: lines.map((l) => l.replace(BULLET, '')) });
    } else {
      // บรรทัดที่ถูกกด Enter ตัดกลางประโยคต่อกลับเป็นย่อหน้าเดียว
      // เพราะกล่องข้อความในเบราว์เซอร์กับกรอบสไลด์กว้างไม่เท่ากัน
      out.push({ kind: 'para', text: lines.join(' ') });
    }
  }
  return out;
}

